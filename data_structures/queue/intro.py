# QUEUE
#----------------------------------------------------
#--- First Come First Out Type Data Structure
#--- Abstract Data Type
#--- Application: Bredth First Search

# Implementation and Operations
#----------------------------------------------------
#--- Can be implemented using list or a LL
#--- Operations
##------------------------------
##--- Enque: Adding/Inserting an element
##--- Deque: Removing/Deleting an element
##--- Size: no of elements
##--- Is empty: empty or not
##--- Front: return element 'next to come out'

# Impltement Queues using List!
# 1. Enque: list.append()
# 2. Front: list[0]
# 3. Deque: list.pop(0)
# 4. Size: len(l1)
# 5. isEmpty: size==0